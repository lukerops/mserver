package router

import (
	"time"

	"github.com/google/uuid"

	"github.com/lukerops/mserver/internal/modules/playback/service"
)

// ErrorV1 is the body of every error response.
type ErrorV1 struct {
	Error string `json:"error"`
}

// PlaybackSessionV1 is an active playback session.
type PlaybackSessionV1 struct {
	ID        uuid.UUID `json:"id"`
	AccountID uuid.UUID `json:"account_id"`
	ProfileID uuid.UUID `json:"profile_id"`
	DeviceID  uuid.UUID `json:"device_id"`
	// ItemID is the library item (movie or episode) being played.
	ItemID uuid.UUID `json:"item_id"`
	// FileID is the storage file being played.
	FileID uuid.UUID `json:"file_id"`
	// PlayMethod is "direct_play".
	PlayMethod string `json:"play_method"`
	PositionMs int64  `json:"position_ms"`
	Paused     bool   `json:"paused"`
	// WatchedMs is the wall-clock time the session played (not paused).
	WatchedMs int64 `json:"watched_ms"`
	// Sequence is the sequence of the last event of the session.
	Sequence  int64     `json:"sequence"`
	StartedAt time.Time `json:"started_at"`
	UpdatedAt time.Time `json:"updated_at"`
	// LastSeenAt is the last report (progress or heartbeat). The session
	// is stopped when it is older than the session timeout.
	LastSeenAt time.Time `json:"last_seen_at"`
}

type PlaybackSessionListV1 struct {
	Sessions []PlaybackSessionV1 `json:"sessions"`
}

// CreatePlaybackSessionRequestV1 starts a session. Its id is generated by
// the server.
type CreatePlaybackSessionRequestV1 struct {
	AccountID uuid.UUID `json:"account_id"`
	ProfileID uuid.UUID `json:"profile_id"`
	DeviceID  uuid.UUID `json:"device_id"`
	ItemID    uuid.UUID `json:"item_id"`
	FileID    uuid.UUID `json:"file_id"`
	// PlayMethod must be "direct_play".
	PlayMethod string `json:"play_method"`
	PositionMs int64  `json:"position_ms"`
	Paused     bool   `json:"paused"`
}

// ProgressRequestV1 reports the state of a session.
type ProgressRequestV1 struct {
	PositionMs int64 `json:"position_ms"`
	Paused     bool  `json:"paused"`
}

// StopRequestV1 stops a session. The body is optional.
type StopRequestV1 struct {
	// PositionMs is the final position; when omitted, the last reported
	// one is kept.
	PositionMs *int64 `json:"position_ms,omitempty"`
}

func toPlaybackSessionV1(s service.Session) PlaybackSessionV1 {
	return PlaybackSessionV1{
		ID:         s.ID,
		AccountID:  s.AccountID,
		ProfileID:  s.ProfileID,
		DeviceID:   s.DeviceID,
		ItemID:     s.ItemID,
		FileID:     s.FileID,
		PlayMethod: s.PlayMethod,
		PositionMs: s.PositionMs,
		Paused:     s.Paused,
		WatchedMs:  s.WatchedMs,
		Sequence:   s.Sequence,
		StartedAt:  s.StartedAt,
		UpdatedAt:  s.UpdatedAt,
		LastSeenAt: s.LastSeenAt,
	}
}
